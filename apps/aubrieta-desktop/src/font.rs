/// Returns the 8-byte row bitmap for an ASCII character.
#[must_use]
pub fn glyph_bitmap(ch: char) -> &'static [u8; 8] {
    let code = ch as usize;
    if (32..=126).contains(&code) {
        &FONT_8X8[code - 32]
    } else {
        // Fallback to square box or question mark
        &FONT_8X8[63 - 32] // '?'
    }
}

/// Draws an ASCII string into a 32-bit pixel buffer with given stride and color.
pub fn draw_text(
    buffer: &mut [u32],
    stride: usize,
    buffer_height: usize,
    start_x: usize,
    start_y: usize,
    text: &str,
    color: u32,
) {
    let mut cursor_x = start_x;
    for ch in text.chars() {
        if ch == '\n' {
            continue;
        }
        let glyph = glyph_bitmap(ch);
        for (row, &row_byte) in glyph.iter().enumerate() {
            let y = start_y + row;
            if y >= buffer_height {
                break;
            }
            for col in 0..8 {
                let x = cursor_x + col;
                if x >= stride {
                    break;
                }
                if (row_byte & (0x80 >> col)) != 0 {
                    buffer[y * stride + x] = color;
                }
            }
        }
        cursor_x += 8;
        if cursor_x >= stride {
            break;
        }
    }
}
